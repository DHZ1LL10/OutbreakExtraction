using System;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace Outbreak.Editor
{
    public static class ImportedAssetAudit
    {
        public static void CleanupAndAudit()
        {
            const string demo="Assets/AssetsStore/Garage_props/Demo/demo.unity";
            if(File.Exists(demo))
            {
                string error=AssetDatabase.MoveAsset(demo,demo+".disabled");
                if(!string.IsNullOrEmpty(error)) throw new InvalidOperationException(error);
            }
            // Only newly imported weapon materials: no change to existing scene materials.
            foreach(var folder in new[]{"Assets/WeaponsPack (LowPoly)","Assets/Low Poly ShotGun Weapon Pack 1"})
            foreach(var guid in AssetDatabase.FindAssets("t:Material",new[]{folder}))
            {
                var material=AssetDatabase.LoadAssetAtPath<Material>(AssetDatabase.GUIDToAssetPath(guid));
                if(material.shader==null || !material.shader.name.StartsWith("Standard",StringComparison.Ordinal)) continue;
                var texture=material.mainTexture; var color=material.color; var scale=material.mainTextureScale; var offset=material.mainTextureOffset;
                float metal=material.HasProperty("_Metallic")?material.GetFloat("_Metallic"):0;
                float smooth=material.HasProperty("_Glossiness")?material.GetFloat("_Glossiness"):0;
                var normal=material.HasProperty("_BumpMap")?material.GetTexture("_BumpMap"):null;
                material.shader=Shader.Find("Universal Render Pipeline/Lit"); material.SetTexture("_BaseMap",texture); material.SetColor("_BaseColor",color);
                material.SetTextureScale("_BaseMap",scale); material.SetTextureOffset("_BaseMap",offset); material.SetFloat("_Metallic",metal); material.SetFloat("_Smoothness",smooth);
                if(normal!=null) { material.SetTexture("_BumpMap",normal); material.EnableKeyword("_NORMALMAP"); }
                EditorUtility.SetDirty(material);
            }
            AssetDatabase.SaveAssets(); Audit();
        }
        public static void Audit()
        {
            var md=new StringBuilder("# Physical asset inventory — Phase 10A\n\nGenerated by Unity 2023.2.20f1. All physical Assets roots are covered; folder names are evidence, not assumed Asset Store purchase names. Prefab/model bounds and scripts are inspected without editing scenes.\n\n");
            var csv=new StringBuilder("path,kind,shader_or_rig,details\n");
            foreach(var folder in Directory.GetDirectories("Assets").OrderBy(p=>p))
            {
                string path=folder.Replace('\\','/');
                var files=Directory.GetFiles(folder,"*",SearchOption.AllDirectories).Where(p=>!p.EndsWith(".meta",StringComparison.OrdinalIgnoreCase)).Select(p=>p.Replace('\\','/')).OrderBy(p=>p).ToArray();
                md.Append("## ").Append(path).Append("\n\n");
                md.Append(string.Join(" · ",files.GroupBy(p=>Path.GetExtension(p).ToLowerInvariant()).OrderBy(g=>g.Key).Select(g=>g.Key+" "+g.Count()))).Append("\n\n");
                foreach(var file in files)
                {
                    string ext=Path.GetExtension(file).ToLowerInvariant(); string kind=ext,info="",details="";
                    if(ext==".mat") { var m=AssetDatabase.LoadAssetAtPath<Material>(file); info=m!=null && m.shader!=null?m.shader.name:"MISSING"; }
                    else if(ext==".prefab" || ext==".fbx")
                    {
                        var model=AssetDatabase.LoadAssetAtPath<GameObject>(file);
                        if(model!=null)
                        {
                            var animator=model.GetComponentInChildren<Animator>(true); var avatar=animator!=null?animator.avatar:null;
                            info=avatar==null?"Static/no avatar":$"Avatar valid={avatar.isValid} human={avatar.isHuman}";
                            int colliders=model.GetComponentsInChildren<Collider>(true).Length;
                            var scripts=model.GetComponentsInChildren<MonoBehaviour>(true).Select(s=>s!=null?s.GetType().FullName:"MISSING SCRIPT");
                            int meshes=model.GetComponentsInChildren<MeshFilter>(true).Length,skins=model.GetComponentsInChildren<SkinnedMeshRenderer>(true).Length;
                            var renderers=model.GetComponentsInChildren<Renderer>(true); var bounds=new Bounds(); bool found=false;
                            foreach(var renderer in renderers) { if(!found) {bounds=renderer.bounds;found=true;} else bounds.Encapsulate(renderer.bounds); }
                            details=$"mesh filters={meshes}; skins={skins}; colliders={colliders}; scale={model.transform.localScale}; bounds={bounds.size}; scripts={string.Join(" / ",scripts)}";
                            if(ext==".fbx") details+="; clips="+string.Join(" / ",AssetDatabase.LoadAllAssetsAtPath(file).OfType<AnimationClip>().Where(c=>!c.name.StartsWith("__preview")).Select(c=>c.name+":"+c.length.ToString("0.00",System.Globalization.CultureInfo.InvariantCulture)+"s"));
                        }
                    }
                    else if(ext==".wav" || ext==".mp3" || ext==".ogg") { var audio=AssetDatabase.LoadAssetAtPath<AudioClip>(file); if(audio!=null) details=$"{audio.length:0.00}s; {audio.channels} channels; {audio.frequency}Hz"; }
                    csv.Append(Q(file)).Append(',').Append(Q(kind)).Append(',').Append(Q(info)).Append(',').Append(Q(details)).Append('\n');
                }
                md.Append("Scenes: ").Append(string.Join(", ",files.Where(p=>p.EndsWith(".unity") || p.EndsWith(".unity.disabled")).Select(p=>"`"+p+"`"))).Append("\n\n");
                md.Append("Materials by shader: ").Append(string.Join("; ",files.Where(p=>p.EndsWith(".mat")).Select(p=>AssetDatabase.LoadAssetAtPath<Material>(p)).Where(m=>m!=null).GroupBy(m=>m.shader!=null?m.shader.name:"MISSING").Select(g=>g.Key+"="+g.Count()))).Append("\n\n");
                md.Append("Prefabs: ").Append(string.Join(", ",files.Where(p=>p.EndsWith(".prefab")).Select(p=>"`"+Path.GetFileNameWithoutExtension(p)+"`"))).Append("\n\n");
            }
            File.WriteAllText("ASSET_CONTENT_INDEX_PHASE10A.csv",csv.ToString(),new UTF8Encoding(false));
            File.WriteAllText("ASSET_PHYSICAL_INVENTORY_PHASE10A.md",md.ToString(),new UTF8Encoding(false));
            Debug.Log("[Phase10A] Vendor demo quarantined; physical asset inventory complete; gameplay scenes not opened.");
        }
        private static string Q(string text)=>"\""+text.Replace("\"","\"\"").Replace("\r"," ").Replace("\n"," ")+"\"";
    }
}
